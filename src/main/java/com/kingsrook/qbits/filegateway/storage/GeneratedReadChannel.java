package com.kingsrook.qbits.filegateway.storage;


import java.io.IOException;
import java.io.InputStream;
import java.nio.ByteBuffer;
import java.nio.channels.ClosedChannelException;
import java.nio.channels.NonWritableChannelException;
import java.nio.channels.SeekableByteChannel;


/*******************************************************************************
 ** A generated stream with a fixed-size rolling window; never regenerates or spools.
 *******************************************************************************/
public final class GeneratedReadChannel implements SeekableByteChannel
{
   /*******************************************************************************
    ** Charge newly consumed bytes and finalize the transfer when its handle closes.
    *******************************************************************************/
   public interface Audit
   {
      /*******************************************************************************
       ** Enforce limits before exposing the newly generated bytes to the client.
       *******************************************************************************/
      void charge(int bytes) throws IOException;

      /*******************************************************************************
       ** Record the final outcome, including stream and seek errors.
       *******************************************************************************/
      void finish(IOException failure) throws IOException;
   }

   private final InputStream input;
   private final byte[] window;
   private final Audit audit;
   private long end;
   private long position;
   private boolean eof;
   private boolean open = true;
   private IOException failure;


   /*******************************************************************************
    ** The supplied stream is owned by this channel from construction through close.
    *******************************************************************************/
   public GeneratedReadChannel(InputStream input, int windowBytes, Audit audit)
   {
      if(windowBytes < 1)
      {
         throw (new IllegalArgumentException("Read-ahead window must be positive"));
      }
      this.input = input;
      this.window = new byte[windowBytes];
      this.audit = audit;
   }


   /*******************************************************************************
    ** Retain the most recent window, including skipped bytes for pipelined reads.
    *******************************************************************************/
   @Override
   public synchronized int read(ByteBuffer destination) throws IOException
   {
      checkOpen();
      int total = 0;
      while(destination.hasRemaining())
      {
         int count = readChunk(destination);
         if(count < 0)
         {
            return (total == 0 ? -1 : total);
         }
         total += count;
      }
      return (total);
   }


   /*******************************************************************************
    ** Fill one ring segment; the public read fills its request to avoid false MINA EOF.
    *******************************************************************************/
   private int readChunk(ByteBuffer destination) throws IOException
   {
      checkOpen();
      if(failure != null)
      {
         throw (failure);
      }
      if(!destination.hasRemaining())
      {
         return (0);
      }
      try
      {
         if(eof && position >= end)
         {
            return (-1);
         }
         if(position < Math.max(0, end - window.length) || position - end >= window.length)
         {
            throw (new IOException("Read outside the generated-file window at " + position + " (stream offset " + end + "); download sequentially"));
         }
         while(position >= end && !eof)
         {
            int offset = (int) (end % window.length);
            int length = (int) Math.min(Math.min(65536, window.length - offset), position - end + Math.min(destination.remaining(), window.length));
            int count = input.readNBytes(window, offset, length);
            if(count == 0)
            {
               eof = true;
            }
            else if(count > 0)
            {
               audit.charge(count);
               end += count;
            }
         }
         if(position >= end)
         {
            return (-1);
         }
         int offset = (int) (position % window.length);
         int count = (int) Math.min(Math.min(destination.remaining(), end - position), window.length - offset);
         destination.put(window, offset, count);
         position += count;
         return (count);
      }
      catch(IOException e)
      {
         failure = e;
         try
         {
            input.close();
         }
         catch(IOException closeError)
         {
            e.addSuppressed(closeError);
         }
         throw (e);
      }
   }


   /*******************************************************************************
    ** Generated content is read-only.
    *******************************************************************************/
   @Override
   public int write(ByteBuffer source)
   {
      throw (new NonWritableChannelException());
   }


   /*******************************************************************************
    ** Current logical read offset.
    *******************************************************************************/
   @Override
   public synchronized long position() throws IOException
   {
      checkOpen();
      return (position);
   }


   /*******************************************************************************
    ** Validate window membership on read, when an actual request is made.
    *******************************************************************************/
   @Override
   public synchronized SeekableByteChannel position(long value) throws IOException
   {
      checkOpen();
      if(value < 0)
      {
         throw (new IllegalArgumentException("Negative read offset"));
      }
      position = value;
      return (this);
   }


   /*******************************************************************************
    ** Generated size is unknown; consumers must read until EOF.
    *******************************************************************************/
   @Override
   public long size() throws IOException
   {
      checkOpen();
      return (0);
   }


   /*******************************************************************************
    ** Generated content cannot be truncated.
    *******************************************************************************/
   @Override
   public SeekableByteChannel truncate(long size)
   {
      throw (new NonWritableChannelException());
   }


   /*******************************************************************************
    ** Handle state.
    *******************************************************************************/
   @Override
   public boolean isOpen()
   {
      return (open);
   }


   /*******************************************************************************
    ** Always close the HTTP stream and finalize exactly one transfer row.
    *******************************************************************************/
   @Override
   public synchronized void close() throws IOException
   {
      if(open)
      {
         open = false;
         try
         {
            input.close();
         }
         catch(IOException e)
         {
            failure = e;
            throw (e);
         }
         finally
         {
            audit.finish(failure);
         }
      }
   }


   /*******************************************************************************
    ** Reject operations after close.
    *******************************************************************************/
   private void checkOpen() throws ClosedChannelException
   {
      if(!open)
      {
         throw (new ClosedChannelException());
      }
   }
}
