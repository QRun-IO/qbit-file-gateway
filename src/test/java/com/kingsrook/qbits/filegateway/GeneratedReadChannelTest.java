package com.kingsrook.qbits.filegateway;


import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.ByteBuffer;
import java.nio.channels.ClosedChannelException;
import java.nio.channels.NonWritableChannelException;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.concurrent.atomic.AtomicReference;
import com.kingsrook.qbits.filegateway.storage.GeneratedReadChannel;
import org.junit.jupiter.api.Test;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;


/*******************************************************************************
 ** Fixed-window stream semantics independently of network packet boundaries and file size.
 *******************************************************************************/
class GeneratedReadChannelTest
{
   /*******************************************************************************
    ** Capture charges and finalization without involving a database.
    *******************************************************************************/
   private GeneratedReadChannel.Audit audit(AtomicInteger bytes, AtomicReference<IOException> failure, AtomicInteger closes)
   {
      return (new GeneratedReadChannel.Audit()
      {
         /*******************************************************************************
          ** Track each newly generated byte once, including forward read-ahead.
          *******************************************************************************/
         public void charge(int count)
         {
            bytes.addAndGet(count);
         }

         /*******************************************************************************
          ** Capture final outcome.
          *******************************************************************************/
         public void finish(IOException error)
         {
            failure.set(error);
            closes.incrementAndGet();
         }
      });
   }


   /*******************************************************************************
    ** Forward gaps and backward reads inside the window reuse bytes without regeneration.
    *******************************************************************************/
   @Test
   void reorderedReadsAndEviction() throws Exception
   {
      byte[] source = new byte[80];
      for(int i = 0; i < source.length; i++)
      {
         source[i] = (byte) i;
      }
      AtomicInteger bytes = new AtomicInteger();
      AtomicInteger closes = new AtomicInteger();
      AtomicReference<IOException> failure = new AtomicReference<>();
      try(var channel = new GeneratedReadChannel(new ByteArrayInputStream(source), 16, audit(bytes, failure, closes)))
      {
         assertThat(channel.size()).isZero();
         channel.position(8);
         ByteBuffer data = ByteBuffer.allocate(4);
         assertThat(channel.read(data)).isEqualTo(4);
         assertThat(data.array()).containsExactly(8, 9, 10, 11);
         channel.position(0);
         data = ByteBuffer.allocate(8);
         assertThat(channel.read(data)).isEqualTo(8);
         assertThat(data.array()).containsExactly(0, 1, 2, 3, 4, 5, 6, 7);
         assertThat(bytes.get()).isEqualTo(12);
         channel.position(12);
         assertThat(channel.read(ByteBuffer.allocate(20))).isEqualTo(20);
         assertThat(channel.position()).isEqualTo(32);
         channel.position(16);
         assertThat(channel.read(ByteBuffer.allocate(4))).isEqualTo(4);
         channel.position(15);
         assertThatThrownBy(() -> channel.read(ByteBuffer.allocate(1))).isInstanceOf(IOException.class).hasMessageContaining("download sequentially");
         assertThatThrownBy(() -> channel.read(ByteBuffer.allocate(1))).isInstanceOf(IOException.class);
      }
      assertThat(closes.get()).isEqualTo(1);
      assertThat(failure.get()).hasMessageContaining("download sequentially");
      assertThat(bytes.get()).isEqualTo(32);
   }


   /*******************************************************************************
    ** Tiny upstream packets cannot falsely signal EOF; only one fixed window is retained.
    *******************************************************************************/
   @Test
   void fullReadsEofAndLifecycle() throws Exception
   {
      AtomicInteger closes = new AtomicInteger();
      AtomicInteger streamCloses = new AtomicInteger();
      AtomicInteger bytes = new AtomicInteger();
      AtomicReference<IOException> failure = new AtomicReference<>();
      InputStream input = new InputStream()
      {
         private int remaining = 100003;

         /*******************************************************************************
          ** Supply bytes one at a time to simulate fragmented HTTP reads.
          *******************************************************************************/
         public int read()
         {
            return (remaining-- > 0 ? 7 : -1);
         }

         /*******************************************************************************
          ** Verify stream ownership.
          *******************************************************************************/
         public void close()
         {
            streamCloses.incrementAndGet();
         }
      };
      var channel = new GeneratedReadChannel(input, 17, audit(bytes, failure, closes));
      ByteBuffer buffer = ByteBuffer.allocate(1024);
      long total = 0;
      int count;
      while((count = channel.read(buffer.clear())) >= 0)
      {
         total += count;
         assertThat(count).isEqualTo(total == 100003 ? 675 : 1024);
      }
      assertThat(total).isEqualTo(100003);
      assertThat(bytes.get()).isEqualTo(100003);
      assertThat(channel.read(ByteBuffer.allocate(0))).isZero();
      assertThatThrownBy(() -> channel.position(-1)).isInstanceOf(IllegalArgumentException.class);
      assertThatThrownBy(() -> channel.write(buffer)).isInstanceOf(NonWritableChannelException.class);
      assertThatThrownBy(() -> channel.truncate(0)).isInstanceOf(NonWritableChannelException.class);
      channel.close();
      channel.close();
      assertThat(channel.isOpen()).isFalse();
      assertThat(closes.get()).isEqualTo(1);
      assertThat(streamCloses.get()).isEqualTo(1);
      assertThat(failure.get()).isNull();
      assertThatThrownBy(channel::position).isInstanceOf(ClosedChannelException.class);
      assertThatThrownBy(channel::size).isInstanceOf(ClosedChannelException.class);
      assertThatThrownBy(() -> channel.read(buffer)).isInstanceOf(ClosedChannelException.class);
   }


   /*******************************************************************************
    ** Invalid windows, excessive forward seeks and underlying read failures are explicit.
    *******************************************************************************/
   @Test
   void failuresCloseAndAudit() throws Exception
   {
      AtomicInteger closes = new AtomicInteger();
      AtomicReference<IOException> failure = new AtomicReference<>();
      var audit = audit(new AtomicInteger(), failure, closes);
      assertThatThrownBy(() -> new GeneratedReadChannel(InputStream.nullInputStream(), 0, audit)).isInstanceOf(IllegalArgumentException.class);
      try(var channel = new GeneratedReadChannel(InputStream.nullInputStream(), 8, audit))
      {
         channel.position(8);
         assertThatThrownBy(() -> channel.read(ByteBuffer.allocate(1))).hasMessageContaining("sequentially");
      }
      try(var channel = new GeneratedReadChannel(new InputStream()
      {
         /*******************************************************************************
          ** Simulate an HTTP transport failure.
          *******************************************************************************/
         public int read() throws IOException
         {
            throw (new IOException("HTTP connection interrupted"));
         }
      }, 8, audit))
      {
         assertThatThrownBy(() -> channel.read(ByteBuffer.allocate(1))).hasMessageContaining("HTTP connection interrupted");
      }
      assertThat(failure.get()).hasMessageContaining("HTTP connection interrupted");
      assertThat(closes.get()).isEqualTo(2);
   }
}
